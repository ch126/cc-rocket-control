"""Deterministic single-file CC build. No network, game writes or calibration."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT=Path(__file__).resolve().parent
MODULES=('recovery_plan','control_allocator','geometry_model','recovery_control','boostback_plan',
         'mission_control','hover_control','mission_runtime','telemetry','engine_io','flight_session','console_view')

def build():
    sources={name:(ROOT/(name+'.lua')).read_text(encoding='utf-8') for name in MODULES}
    home=(ROOT/'home.lua').read_text(encoding='utf-8')
    boundary='if args[1]=="--test" then return M end'
    assert home.count(boundary)==1, 'Math-module boundary changed; review bundle extraction'
    sources['home_math']=home.split(boundary)[0]+'return M\n'
    app=(ROOT/'rocket_app.lua').read_text(encoding='utf-8')
    digest=hashlib.sha256(json.dumps([sources,app],sort_keys=True).encode()).hexdigest()
    parts=['-- GENERATED by build_bundle.py; edit source modules, not this file.\n',
           '-- Source SHA256: '+digest+'\n',
           '-- Default read-only. Live mode is experimental and requires measured configuration.\n',
           'local factories,loaded={},{}\n',
           'local function require(name)\n'
           '  if loaded[name]~=nil then return loaded[name] end\n'
           '  local factory=assert(factories[name],"Module not bundled: "..tostring(name))\n'
           '  loaded[name]=factory(); return loaded[name]\nend\n']
    for name,source in sources.items():
        parts.append('factories['+json.dumps(name)+']=function(...)\n'+source+'\nend\n')
    parts.append('local function loadfile(name)\n'
                 '  assert(name=="home.lua","Only embedded math is available")\n'
                 '  return factories.home_math\nend\n')
    parts.append(app)
    return ''.join(parts)

if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true')
    args=parser.parse_args(); content=build(); target=ROOT/'rocket_bundle.lua'
    if args.check:
        assert target.read_text(encoding='utf-8')==content, 'Bundle stale: run build_bundle.py'
        print('PASS: bundle matches all current source modules')
    else:
        target.write_text(content,encoding='utf-8',newline='\n')
        print('Built rocket_bundle.lua:',len(content.encode()),'bytes')
